#!/usr/bin/env node
/*
 * Looks in public/models/ for .glb / .gltf files from a CC0 art pack (Kenney City Kit Suburban,
 * KayKit City Builder Bits, ...) and writes public/models/manifest.json so the app only asks
 * for files that really exist (no 404s, no console errors). Runs before `npm run dev` and `npm run build`.
 *
 * Roles the city can use: house, tree, lamp, car, bench.
 * To pick files by hand, create public/models/roles.json, e.g.
 *   { "house": ["building-type-a.glb", "building-type-c.glb"], "tree": ["tree-large.glb"] }
 */
import { readdirSync, statSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join, relative, basename } from 'node:path';

const root = join(process.cwd(), 'public', 'models');
const files = [];
function walk(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(glb|gltf)$/i.test(name)) files.push(relative(root, p).split('\\').join('/'));
  }
}
walk(root);
files.sort();

const RULES = {
  house: { re: /(building|house|home)/i, not: /(garage|road|path|fence|tree|base|wall|roof|door|window|sign)/i },
  tree: { re: /tree/i, not: /(stump|log)/i },
  lamp: { re: /(lamp|street[-_ ]?light|light[-_ ]?post|streetlight)/i, not: null },
  car: { re: /(^|[-_ /])(car|truck|van|taxi|sedan|suv|hatchback|stationwagon|police)([-_ .]|$)/i, not: /(cart|card|carpet|wheel)/i },
  bench: { re: /bench/i, not: null }
};
const roles = {};
for (const [role, r] of Object.entries(RULES)) {
  roles[role] = files.filter((f) => r.re.test(basename(f)) && !(r.not && r.not.test(basename(f)))).slice(0, 24);
}
const overrideFile = join(root, 'roles.json');
if (existsSync(overrideFile)) {
  try {
    const o = JSON.parse(readFileSync(overrideFile, 'utf8'));
    for (const [role, list] of Object.entries(o)) roles[role] = [].concat(list).filter((f) => files.includes(f));
  } catch (e) {
    console.warn('[models] roles.json could not be read:', e.message);
  }
}
writeFileSync(join(root, 'manifest.json'), JSON.stringify({ note: 'Generated by scripts/scan-models.mjs. Do not edit; add roles.json instead.', files, roles }, null, 2) + '\n');
const used = Object.entries(roles).map(([k, v]) => `${k}: ${v.length}`).join(', ');
console.log(`[models] ${files.length} model file(s) found. Using ${used || 'none'} (code-made models fill in the rest).`);
